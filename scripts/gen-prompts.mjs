#!/usr/bin/env node
// Bundles skills/cotsi (SKILL.md + references) into a TypeScript module for the API,
// so the web app teaches from the same source as the skill. Run after editing the skill:
//   node scripts/gen-prompts.mjs
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const skillDir = join(root, "skills", "cotsi");
const out = join(root, "supabase", "functions", "api", "src", "prompts.generated.ts");

const skill = readFileSync(join(skillDir, "SKILL.md"), "utf8");
const m = skill.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
if (!m) throw new Error("SKILL.md has no frontmatter");
const version = (m[1].match(/version:\s*"?([\d.]+)"?/) || [])[1] || "0";
const body = m[2].trim();

const refs = readdirSync(join(skillDir, "references")).filter((f) => f.endsWith(".md")).sort();
const parts = [body];
for (const f of refs) {
  parts.push(`\n\n---\n\n<reference file="references/${f}">\n${readFileSync(join(skillDir, "references", f), "utf8").trim()}\n</reference>`);
}
const text = parts.join("");
writeFileSync(
  out,
  `// GENERATED by scripts/gen-prompts.mjs from skills/cotsi. Do not edit by hand.\n` +
    `export const COTSI_SKILL_VERSION = ${JSON.stringify(version)};\n` +
    `export const COTSI_SKILL = ${JSON.stringify(text)};\n`,
);
console.log(`wrote ${out} (skill ${version}, ${text.split(/\s+/).length} words, ${refs.length} references)`);
